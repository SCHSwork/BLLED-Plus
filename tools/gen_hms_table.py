#!/usr/bin/env python3
"""Build the printer error descriptions the status page shows next to an error code.

Source: tools/hms/hms_en.json.gz and wiki_links.json.gz from the ha-bambulab project
(https://github.com/greghesp/ha-bambulab, MIT license), which collects Bambu Lab's own
descriptions (the ones Bambu Studio and the printer screen show). To refresh, copy newer
versions of those two files into tools/hms/ and run: python3 tools/gen_hms_table.py

Writes:
- src/blled/hms_table.h: the table gzipped, built into the full edition and served at /hms.json
- docs/hms_en.json: the same table, which the lite edition's status page reads from GitHub

Table format (compact JSON):
  {"h": {"<16 hex HMS code>": entry}, "e": {"<8 hex print error>": entry}, "w": {"<code>": "<wiki path>"}}
  entry = "text" when every printer gets the same text, otherwise [["text", "H2D,H2S"], ...]
  where an empty model list means "any other printer".
"""
import gzip, json, os

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
src = json.load(gzip.open(os.path.join(here, 'hms', 'hms_en.json.gz')))
wiki = json.load(gzip.open(os.path.join(here, 'hms', 'wiki_links.json.gz')))


def entry(v):
    items = [(msg.strip(), ','.join(models)) for msg, models in v.items() if msg.strip()]
    if not items:
        return None
    if len(items) == 1 and not items[0][1]:
        return items[0][0]
    return [list(i) for i in items]


table = {'h': {}, 'e': {}, 'w': {}}
for key, out in (('device_hms', 'h'), ('device_error', 'e')):
    for code, v in sorted(src.get(key, {}).items()):
        e = entry(v)
        if e:
            table[out][code.upper()] = e
for code, v in sorted(wiki.items()):
    # keep the general page for each code (the one with no model list, else the first)
    paths = sorted(v.items(), key=lambda kv: len(kv[1]) > 0)
    if paths:
        table['w'][code.upper()] = paths[0][0]

data = json.dumps(table, separators=(',', ':'), ensure_ascii=False).encode('utf-8')
gz = gzip.compress(data, 9, mtime=0)

with open(os.path.join(root, 'docs', 'hms_en.json'), 'wb') as f:
    f.write(data)
with open(os.path.join(root, 'src', 'blled', 'hms_table.h'), 'w') as f:
    f.write('// Generated by tools/gen_hms_table.py from Bambu Lab\'s error descriptions (via ha-bambulab, MIT). Do not edit.\n')
    f.write('#pragma once\n#include <pgmspace.h>\n#ifndef BLLED_LITE\n')
    f.write('const uint8_t hmsTableGz[] PROGMEM = {\n')
    for i in range(0, len(gz), 20):
        f.write('  ' + ','.join('0x%02x' % b for b in gz[i:i + 20]) + ',\n')
    f.write('};\nconst size_t hmsTableGzLen = %d;\n#endif\n' % len(gz))
print('%d HMS codes, %d print errors, %d wiki links: %d bytes, %d gzipped'
      % (len(table['h']), len(table['e']), len(table['w']), len(data), len(gz)))
