#!/usr/bin/env python3
"""Build src/blled/cert_bundle.h: the trusted root certificates the controller uses to check it is
really talking to GitHub when it downloads an update. Same format as ESP-IDF's gen_crt_bundle.py
(count, then per certificate: subject length, key length, subject DER, public key DER), sorted by
subject so the firmware can binary-search it. Source: Mozilla's root list (python certifi).

Two lists go in the header:
- full edition: all of Mozilla's roots (~55 KB), so it keeps working whoever GitHub moves to
- lite edition (BLLED_LITE): only the authorities GitHub uses (~5 KB), so the firmware fits
  controllers on the original BLLED storage layout

Usage: tools/gen_cert_bundle.py [older-cacert.pem]
The optional older cacert.pem adds roots that left Mozilla's list but still anchor cross-signed
chains GitHub's servers have used (DigiCert G1, Comodo AAA), plus GlobalSign Root CA for Google
Trust Services chains (Discord)."""
import sys, certifi
from cryptography import x509
from cryptography.hazmat.primitives import serialization

# GlobalSign Root CA (R1): left Mozilla's list, but Google Trust Services chains (Discord and every
# other site behind Google's certificates) still send GTS Root R1/R4 cross-signed by it, and the
# controller only checks the top certificate the server sends
LEGACY = ('DigiCert Global Root CA', 'DigiCert High Assurance EV Root CA', 'AAA Certificate Services',
          'CN=GlobalSign Root CA,OU=Root CA')
GITHUB = ('USERTrust ECC Certification Authority', 'USERTrust RSA Certification Authority',
          'AAA Certificate Services', 'Sectigo Public Server Authentication Root E46',
          'Sectigo Public Server Authentication Root R46', 'DigiCert Global Root CA',
          'DigiCert Global Root G2', 'DigiCert Global Root G3', 'DigiCert High Assurance EV Root CA',
          'DigiCert TLS ECC P384 Root G5', 'DigiCert TLS RSA4096 Root G5', 'ISRG Root X1', 'ISRG Root X2')

certs = x509.load_pem_x509_certificates(open(certifi.where(), 'rb').read())
if len(sys.argv) > 1:
    for c in x509.load_pem_x509_certificates(open(sys.argv[1], 'rb').read()):
        if any(n in c.subject.rfc4514_string() for n in LEGACY):
            certs.append(c)


def bundle(certs):
    entries = {}
    for c in certs:
        key = c.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
        entries[c.subject.public_bytes()] = key
    data = bytearray(len(entries).to_bytes(2, 'big'))
    for name in sorted(entries):
        key = entries[name]
        data += len(name).to_bytes(2, 'big') + len(key).to_bytes(2, 'big') + name + key
    return len(entries), data


def array(data):
    return ''.join('  ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',\n' for i in range(0, len(data), 16))


full_n, full = bundle(certs)
lite_n, lite = bundle([c for c in certs if any('CN=' + k in c.subject.rfc4514_string() for k in GITHUB)])
out = 'src/blled/cert_bundle.h'
with open(out, 'w') as f:
    f.write('// Generated by tools/gen_cert_bundle.py from Mozilla\'s root certificates. Do not edit.\n')
    f.write('#pragma once\n#include <pgmspace.h>\n#ifdef BLLED_LITE\n')
    f.write('// Lite edition: the %d roots GitHub uses\nconst uint8_t certBundle[] PROGMEM = {\n%s};\n' % (lite_n, array(lite)))
    f.write('#else\n')
    f.write('// Full edition: all %d roots\nconst uint8_t certBundle[] PROGMEM = {\n%s};\n' % (full_n, array(full)))
    f.write('#endif\n')
print('full: %d roots, %d bytes; lite: %d roots, %d bytes -> %s' % (full_n, len(full), lite_n, len(lite), out))
