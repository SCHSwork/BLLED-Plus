#!/usr/bin/env python3
"""Build src/blled/cert_bundle.h: the trusted root certificates (only those GitHub uses) the controller uses to check it is
really talking to GitHub when it downloads an update. Same format as ESP-IDF's gen_crt_bundle.py
(count, then per certificate: subject length, key length, subject DER, public key DER), sorted by
subject so the firmware can binary-search it. Source: Mozilla's root list (python certifi)."""
import sys, certifi
from cryptography import x509
from cryptography.hazmat.primitives import serialization

pem = open(certifi.where(), 'rb').read()
certs = x509.load_pem_x509_certificates(pem)
# Older roots (DigiCert G1, Comodo AAA) left Mozilla's list but still anchor some cross-signed chains (GitHub's
# download servers have used them). Pass an older cacert.pem as the second argument to add them.
LEGACY = ('DigiCert Global Root CA', 'DigiCert High Assurance EV Root CA', 'AAA Certificate Services')
if len(sys.argv) > 2:
    for c in x509.load_pem_x509_certificates(open(sys.argv[2], 'rb').read()):
        if any(n in c.subject.rfc4514_string() for n in LEGACY):
            certs.append(c)
# Only the authorities GitHub's API and download servers chain to (plus their usual cross-signs and
# successors). The full Mozilla list is ~55 KB; this keeps the firmware small enough for
# controllers on the original BLLED storage layout.
KEEP = ('USERTrust ECC Certification Authority', 'USERTrust RSA Certification Authority',
        'AAA Certificate Services', 'Sectigo Public Server Authentication Root E46',
        'Sectigo Public Server Authentication Root R46', 'DigiCert Global Root CA',
        'DigiCert Global Root G2', 'DigiCert Global Root G3', 'DigiCert High Assurance EV Root CA',
        'DigiCert TLS ECC P384 Root G5', 'DigiCert TLS RSA4096 Root G5', 'ISRG Root X1', 'ISRG Root X2')
certs = [c for c in certs if any('CN=' + k in c.subject.rfc4514_string() for k in KEEP)]
entries = {}
for c in certs:
    name = c.subject.public_bytes()
    key = c.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
    entries[name] = key
data = bytearray(len(entries).to_bytes(2, 'big'))
for name in sorted(entries):
    key = entries[name]
    data += len(name).to_bytes(2, 'big') + len(key).to_bytes(2, 'big') + name + key
out = sys.argv[1] if len(sys.argv) > 1 else 'src/blled/cert_bundle.h'
with open(out, 'w') as f:
    f.write('// Generated by tools/gen_cert_bundle.py from Mozilla\'s root certificates (%d roots GitHub uses). Do not edit.\n' % len(entries))
    f.write('#pragma once\n#include <pgmspace.h>\nconst uint8_t certBundle[] PROGMEM = {\n')
    for i in range(0, len(data), 16):
        f.write('  ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',\n')
    f.write('};\n')
print(len(entries), 'roots,', len(data), 'bytes ->', out)
